import { ecfToLookAngles } from 'satellite.js';
import { describe, expect, it } from 'vitest';
import { degToRad, geodeticToEcef, radToDeg } from './geodetic';
import { compassPoint, createObserver, lookAngles } from './topocentric';

describe('lookAngles', () => {
  it('puts a point straight above the observer at the zenith', () => {
    for (const [lat, lon] of [
      [0, 0],
      [33.75, -84.39],
      [-33.87, 151.21],
      [89, 10],
    ] as const) {
      const observer = createObserver(degToRad(lat), degToRad(lon), 0.2);
      // "Straight above" means along the ellipsoid normal: same latitude and longitude, higher.
      const above = geodeticToEcef(degToRad(lat), degToRad(lon), 400.2);
      const look = lookAngles(observer, above.x, above.y, above.z);
      expect(radToDeg(look.elevationRad)).toBeCloseTo(90, 5);
      expect(look.rangeKm).toBeCloseTo(400, 6);
    }
  });

  it('gives the compass bearing of points a short way north, east, south and west', () => {
    const observer = createObserver(degToRad(40), degToRad(-75), 0);
    const bearingTo = (lat: number, lon: number): number => {
      const p = geodeticToEcef(degToRad(lat), degToRad(lon), 300);
      return radToDeg(lookAngles(observer, p.x, p.y, p.z).azimuthRad);
    };
    // Due north may come out as 0 or as a hair under 360; both are north.
    expect(Math.cos(degToRad(bearingTo(41, -75)))).toBeCloseTo(1, 12);
    expect(Math.sin(degToRad(bearingTo(41, -75)))).toBeCloseTo(0, 8);
    expect(bearingTo(39, -75)).toBeCloseTo(180, 6);
    // Due east and west along a parallel of latitude are not exactly 90 and
    // 270 degrees, because a parallel curves towards the pole; half a degree
    // of longitude keeps that effect under a quarter of a degree.
    expect(bearingTo(40, -74.5)).toBeGreaterThan(89.7);
    expect(bearingTo(40, -74.5)).toBeLessThan(90);
    expect(bearingTo(40, -75.5)).toBeGreaterThan(270);
    expect(bearingTo(40, -75.5)).toBeLessThan(270.3);
  });

  it('puts a point on the far side of the Earth below the horizon', () => {
    const observer = createObserver(degToRad(10), degToRad(20), 0);
    const far = geodeticToEcef(degToRad(-10), degToRad(-160), 400);
    expect(lookAngles(observer, far.x, far.y, far.z).elevationRad).toBeLessThan(-1.4);
  });

  it('agrees with the independent implementation in satellite.js', () => {
    // A spread of observers and of points from low orbit to geostationary
    // height, generated by a fixed rule so that the test is repeatable.
    let worstAngleDeg = 0;
    let worstRangeKm = 0;
    let compared = 0;
    for (let i = 0; i < 400; i += 1) {
      const lat = -85 + ((i * 37) % 171);
      const lon = -180 + ((i * 53) % 360);
      const height = (i % 5) * 0.8;
      const observer = createObserver(degToRad(lat), degToRad(lon), height);
      const pointLat = -80 + ((i * 29) % 161);
      const pointLon = -180 + ((i * 71) % 360);
      const pointHeight = 300 + ((i * 997) % 35_500);
      const p = geodeticToEcef(degToRad(pointLat), degToRad(pointLon), pointHeight);

      const mine = lookAngles(observer, p.x, p.y, p.z);
      const theirs = ecfToLookAngles(
        { latitude: degToRad(lat), longitude: degToRad(lon), height },
        p,
      );
      worstRangeKm = Math.max(worstRangeKm, Math.abs(mine.rangeKm - theirs.rangeSat));
      worstAngleDeg = Math.max(
        worstAngleDeg,
        Math.abs(radToDeg(mine.elevationRad - theirs.elevation)),
      );
      // Azimuth is undefined at the zenith and wraps at north.
      if (Math.abs(radToDeg(mine.elevationRad)) < 89) {
        const difference = Math.abs(radToDeg(mine.azimuthRad - theirs.azimuth)) % 360;
        worstAngleDeg = Math.max(worstAngleDeg, Math.min(difference, 360 - difference));
      }
      compared += 1;
    }
    expect(compared).toBe(400);
    // A ten-millionth of a degree: the two differ only by rounding.
    expect(worstAngleDeg).toBeLessThan(1e-7);
    expect(worstRangeKm).toBeLessThan(1e-7);
  });
});

describe('compassPoint', () => {
  it('names the nearest of sixteen points', () => {
    expect(compassPoint(0)).toBe('N');
    expect(compassPoint(11)).toBe('N');
    expect(compassPoint(12)).toBe('NNE');
    expect(compassPoint(90)).toBe('E');
    expect(compassPoint(135)).toBe('SE');
    expect(compassPoint(202.5)).toBe('SSW');
    expect(compassPoint(292)).toBe('WNW');
    expect(compassPoint(349)).toBe('N');
    expect(compassPoint(348)).toBe('NNW');
    expect(compassPoint(360)).toBe('N');
    expect(compassPoint(-90)).toBe('W');
    expect(compassPoint(725)).toBe('N');
  });
});
